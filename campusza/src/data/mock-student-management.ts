// Dashboard summary data
export const getDashboardSummary = () => {
  const pendingFees = studentTermRecords.filter(r => r.fee.status !== "paid");
  const pendingCertificates = studentTermRecords.flatMap(r => r.certificates).filter(c => c.status === "pending");
  const totalFeesDue = pendingFees.reduce((sum, r) => sum + (r.fee.totalAmount - r.fee.paidAmount), 0);
  const totalFeesCollected = studentTermRecords.reduce((sum, r) => sum + r.fee.paidAmount, 0);

  return {
    pendingFeesCount: pendingFees.length,
    pendingCertificatesCount: pendingCertificates.length,
    totalFeesDue,
    totalFeesCollected,
    totalStudentsAssigned: studentTermRecords.length,
    activeTerm: termsData.find(t => t.status === "active"),
  };
};

